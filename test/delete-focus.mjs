import { chromium } from 'playwright-core';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const executablePath = process.env.CHROME_PATH || path.join(os.homedir(), 'AppData/Local/ms-playwright/chromium-1234/chrome-win64/chrome.exe');
const browser=await chromium.launch({executablePath, headless:true});
const page=await browser.newPage({viewport:{width:1400,height:1000}});
const errors=[]; page.on('pageerror',e=>errors.push(String(e)));
const check=(name,condition)=>{console.log((condition?'PASS ':'FAIL ')+name);if(!condition)process.exitCode=1;};
await page.goto('file:///'+path.join(dir,'harness.html').replace(/\\/g,'/'));
const md='---\ncloudmind: true\n---\n# 根主题\n## 孩子\n## 另一个\n';
await page.evaluate(md=>window.boot(md),md);
await page.waitForFunction(()=>window.hasMM());
await page.waitForTimeout(500);
await page.evaluate(()=>{window.__first=window.__view;window.__first.mm.renderer.root.active()});
await page.evaluate(md=>window.bootSecond(md),md);
await page.waitForFunction(()=>window.__second?.mm?.renderer?.root?.children?.length);
await page.waitForTimeout(500);
await page.evaluate(()=>window.__second.mm.renderer.root.children[0].active());
await page.keyboard.press('F2');
await page.waitForFunction(()=>window.__second.mm.renderer.textEdit.isShowTextEdit());
await page.keyboard.press('End');
const before=await page.locator('.smm-node-edit-wrap').last().textContent();
await page.keyboard.press('Backspace');
const after=await page.locator('.smm-node-edit-wrap').last().textContent();
check('Other view root selected: Backspace deletes text without warning', after===before.slice(0,-1) && !(await page.evaluate(()=>window.__notices||[])).length);
await page.keyboard.press('Enter');
await page.waitForTimeout(300);
check('Edited node is saved, old view retains its nodes',await page.evaluate(()=>window.__second.getViewData().includes('## 孩') && window.__first.mm.renderer.root.children.length===2));
await page.evaluate(()=>{window.__first.mm.execCommand('CLEAR_ACTIVE_NODE');window.__first.mm.renderer.root.children[0].active();window.__second.mm.execCommand('CLEAR_ACTIVE_NODE');window.__second.mm.renderer.root.children[1].active();document.body.focus();});
await page.keyboard.press('Backspace');
await page.waitForTimeout(300);
check('Backspace removes only the selected node in the active map',await page.evaluate(()=>window.__first.mm.renderer.root.children.length===2 && window.__second.mm.renderer.root.children.length===1));
await page.evaluate(()=>{window.__second.mm.execCommand('CLEAR_ACTIVE_NODE');document.body.focus();});
await page.keyboard.press('Backspace');
await page.waitForTimeout(200);
check('No selection in the active map does not delete a selection in the inactive map',await page.evaluate(()=>window.__first.mm.renderer.root.children.length===2));
await page.evaluate(()=>{window.__second.mm.renderer.root.children[0].active();document.body.dispatchEvent(new KeyboardEvent('keydown',{key:'Backspace',code:'Backspace',keyCode:8,bubbles:true,cancelable:true,isComposing:true}));});
await page.waitForTimeout(200);
check('Composition Backspace never deletes nodes, even with keyCode 8',await page.evaluate(()=>window.__first.mm.renderer.root.children.length===2 && window.__second.mm.renderer.root.children.length===1));
await page.evaluate(()=>{window.__second.mm.execCommand('CLEAR_ACTIVE_NODE');window.__second.mm.renderer.root.active();window.__notices=[];});
await page.keyboard.press('Backspace');
check('Active central topic stays protected',await page.evaluate(()=>window.__second.mm.renderer.root.children.length===1 && window.__notices.includes('中心主题不能删除')));
await page.evaluate(()=>{const input=document.createElement('input');input.id='other-input';input.value='abc';document.body.appendChild(input);input.focus();input.setSelectionRange(3,3);window.__notices=[];});
await page.keyboard.press('Backspace');
check('Backspace in another input is not intercepted',await page.evaluate(()=>document.querySelector('#other-input').value==='ab' && !window.__notices.length));
check('No browser errors',errors.length===0);
if(errors.length)console.log(errors);
await browser.close();
